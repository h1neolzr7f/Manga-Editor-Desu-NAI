test('credentials and provider response bodies never enter persisted job records', async () => {
  const { context, client, jobs, storage } = setup();
  const secret = 'sk-test-super-secret-value';
  context.NaiImage2ProviderRegistry.register({ id: 'mock', generate: async () => { throw new Error('Authorization: Bearer ' + secret + ' raw upstream request'); } });
  await assert.rejects(client.submit({ providerId: 'mock', apiKey: secret, credentials: { token: secret } }));
  jobs.update(jobs.list()[0].id, { apiKey: secret, credentials: { token: secret }, error: 'Bearer ' + secret });
  assert.ok(!JSON.stringify(jobs.list()).includes(secret));
  assert.ok(!storage.get('nai_comic_image2_jobs_v1').includes(secret));
  storage.set('nai_comic_image2_jobs_v1', JSON.stringify([{ ...jobs.list()[0], apiKey: secret, error: 'Bearer ' + secret }]));
  const reloaded = new context.NaiImage2JobStore();
  assert.ok(!JSON.stringify(reloaded.list()).includes(secret));
  assert.ok(!storage.get('nai_comic_image2_jobs_v1').includes(secret));
});
