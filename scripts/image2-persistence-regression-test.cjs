test('explicit failed retry updates same job and counts real provider attempts', async () => {
  const { context, client, jobs } = setup(); let calls = 0;
  context.NaiImage2ProviderRegistry.register({ id: 'mock', generate: async () => { if (++calls === 1) throw new Error('provider failed'); return { image: PNG }; } });
  await assert.rejects(client.submit({ providerId: 'mock' }));
  const job = jobs.list()[0];
  const result = await client.retry(job.id);
  assert.equal(result.job.id, job.id);
  assert.equal(jobs.list().length, 1);
  assert.equal(result.job.attempts, 2);
  await assert.rejects(client.retry(job.id));
  assert.equal(calls, 2, 'successful retry must never generate again');
});
test('overlapping retry across clients makes one provider call', async () => {
  const { context, client, jobs } = setup(); let calls = 0, release;
  context.NaiImage2ProviderRegistry.register({ id: 'mock', generate: async () => { calls++; if (calls === 1) throw new Error('fail'); return new Promise(resolve => { release = () => resolve({ image: PNG }); }); } });
  await assert.rejects(client.submit({ providerId: 'mock' }));
  const id = jobs.list()[0].id;
  const retry = client.retry(id);
  await Promise.resolve();
  const duplicate = new context.NaiImage2Client().retry(id);
  await assert.rejects(Promise.race([duplicate, new Promise(resolve => setTimeout(() => resolve('not rejected'), 20))]));
  release(); await retry;
  assert.equal(calls, 2);
});
test('persistence retry reuses generated bytes without another paid generation', async () => {
  const { context, client, jobs, assets } = setup(); let calls = 0;
  context.NaiImage2ProviderRegistry.register({ id: 'mock', generate: async () => { calls++; return { image: PNG }; } });
  context.NaiComicAssetBlobStore.put = async () => false;
  await assert.rejects(client.submit({ providerId: 'mock' }));
  const failed = jobs.list()[0];
  assert.equal(failed.status, 'failed');
  assert.equal(assets.list().length, 0, 'failed durability must not leave a phantom asset');
  context.NaiComicAssetBlobStore.put = async () => true;
  const result = await client.retry(failed.id);
  assert.equal(result.job.attempts, 1);
  assert.equal(result.job.id, failed.id);
  assert.equal(calls, 1);
});
