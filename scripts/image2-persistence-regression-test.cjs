function setup() {
  const storage = new Map(), blobs = new Map();
  class Reader {
    readAsDataURL(blob) {
      blob.arrayBuffer().then(bytes => {
        this.result = 'data:' + blob.type + ';base64,' + Buffer.from(bytes).toString('base64');
        if (this.onload) this.onload({ target: this });
      }).catch(() => this.onerror && this.onerror());
    }
  }
  const context = { console, Date, Math, JSON, Object, Array, Promise, Set, Map, Blob, Uint8Array, ArrayBuffer, atob, FileReader: Reader, localStorage: { getItem: k => storage.get(k) || null, setItem: (k, v) => storage.set(k, v) } };
  context.globalThis = context;
  for (const file of ['asset-manifest', 'asset-store', 'image2-job-store', 'image2-client']) vm.runInNewContext(fs.readFileSync('js/assets/' + file + '.js', 'utf8'), context, { filename: file });
  context.NaiComicAssetBlobStore = { put: async (id, blob, meta) => { blobs.set(id, { id, blob, ...meta }); return true; }, all: async () => [...blobs.values()], toFile: entry => entry.blob, remove: async id => blobs.delete(id) };
  return { context, storage, blobs, client: new context.NaiImage2Client(), jobs: context.NaiImage2JobStoreDefault, assets: context.NaiComicAssetStoreDefault };
}
const tests = [];
function test(name, fn) { tests.push([name, fn]); }
test('returned data image is a durable file, usable after manifest reload', async () => {
  const { context, blobs, client, assets } = setup();
  context.NaiImage2ProviderRegistry.register({ id: 'mock', generate: async () => ({ image: PNG }) });
  const result = await client.submit({ providerId: 'mock', assetName: 'portrait' });
  assert.ok(assets.files.has(result.asset.id), 'generated bytes must be in the file map');
  assert.ok(blobs.has(result.asset.id), 'generated bytes must persist to blob storage');
  assert.equal(result.asset.path, '', 'do not invent a server path');
  assert.equal(await assets.getDataUrl(result.asset.id), PNG);
  const restored = new context.NaiComicAssetStore();
  await restored.hydrateBlobs();
  assert.equal(await restored.getDataUrl(result.asset.id), PNG);
});
