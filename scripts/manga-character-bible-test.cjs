const assert=require('node:assert/strict');
const fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const ctx={window:{},console};
vm.runInNewContext(fs.readFileSync(path.join(__dirname,'../js/ai/manga-character-bible-core.js'),'utf8'),ctx);
const lib=ctx.window.MangaCharacterBibleCore;
assert(lib);
const png='data:image/png;base64,'+Buffer.from('not-a-real-image-bytes-because-contract-verifies-container-not-decoding').toString('base64');
const card=lib.normalize({id:'role_a',name:'  主角  ',traits:'金色太阳眼镜、黑色大衣',notes:'战斗形态',references:[png]});
assert.equal(card.name,'主角');
assert.equal(card.references.length,1);
assert.equal(lib.fromDocument(lib.toDocument([card]))[0].id,'role_a');
const prompt=lib.withCharacterPrompt('第二格替换人物',card);
assert(prompt.includes('金色太阳眼镜'));
assert(prompt.includes('第二格替换人物'));
assert(!JSON.stringify(lib.toDocument([card])).includes('API_KEY'));
assert.throws(()=>lib.normalize({...card,references:['javascript:alert(1)']}),/图片无效/);
assert.throws(()=>lib.normalize({...card,references:[]}),/至少一张/);
assert.throws(()=>lib.normalize({...card,id:'../../bad'}),/ID 无效/);
assert.throws(()=>lib.normalize({...card,name:'  '}),/名称不能为空/);
assert.throws(()=>lib.normalize({...card,references:[png,png,png,png]}),/3 张/);
assert.throws(()=>lib.fromDocument({...lib.toDocument([card]),characters:[card,card]}),/重复 ID/);
assert.throws(()=>lib.fromDocument({schemaVersion:987,characters:[card]}),/不受支持/);
assert.throws(()=>lib.toDocument(Array(25).fill(card)),/超过上限/);
console.log('PASS character bible schema, local reference filters, import/export and constrained prompts');
